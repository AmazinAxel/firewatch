#!/usr/bin/env python3
"""Convert icons/*.svg into 1-bit bitmap headers (include/generated/icons.h).

The generated header is committed, so this only needs to run when an SVG
changes. Requires `rsvg-convert` and Pillow — run inside `nix develop`:

    python3 scripts/gen_icons.py

Bitmap format: row-major, rows padded to whole bytes, MSB first, bit set =
ink (drawn by Adafruit_GFX drawBitmap with the foreground color).

The wind arrow SVG points north; eight rotations (one per compass octant)
are generated by supersampled raster rotation so the firmware just indexes
ICON_ARROW_*[octant].
"""

import io
import os
import subprocess
import sys

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ICONS = os.path.join(ROOT, "icons")
OUT = os.path.join(ROOT, "include", "generated", "icons.h")

# Must match the WeatherIcon enum in src/model.h.
WEATHER = [
    ("sun", "ICO_SUN"),
    ("moon", "ICO_MOON"),
    ("partly_day", "ICO_PARTLY_DAY"),
    ("partly_night", "ICO_PARTLY_NIGHT"),
    ("cloud", "ICO_CLOUD"),
    ("fog", "ICO_FOG"),
    ("drizzle", "ICO_DRIZZLE"),
    ("rain", "ICO_RAIN"),
    ("snow", "ICO_SNOW"),
    ("thunder", "ICO_THUNDER"),
]
WEATHER_SIZES = [64, 28]
ARROW_SIZES = [28, 20]
REFRESH_SIZE = 36
SUPERSAMPLE = 4
THRESHOLD = 128  # alpha >= this = ink


def render_svg(name: str, px: int) -> Image.Image:
    """Render an SVG to an RGBA image of px * px."""
    svg = os.path.join(ICONS, name + ".svg")
    png = subprocess.run(
        ["rsvg-convert", "-w", str(px), "-h", str(px), svg],
        check=True,
        capture_output=True,
    ).stdout
    return Image.open(io.BytesIO(png)).convert("RGBA")


def to_bits(img: Image.Image) -> bytes:
    """Alpha-threshold an RGBA image into padded 1-bit rows."""
    alpha = img.getchannel("A")
    w, h = img.size
    row_bytes = (w + 7) // 8
    out = bytearray(row_bytes * h)
    px = alpha.load()
    for y in range(h):
        for x in range(w):
            if px[x, y] >= THRESHOLD:
                out[y * row_bytes + x // 8] |= 0x80 >> (x % 8)
    return bytes(out)


def rotated_arrow(px: int, angle_cw: float) -> Image.Image:
    """Arrow pointing `angle_cw` degrees clockwise from north."""
    big = render_svg("wind_arrow", px * SUPERSAMPLE)
    big = big.rotate(-angle_cw, resample=Image.BICUBIC)  # PIL rotates CCW
    return big.resize((px, px), Image.LANCZOS)


def emit_array(f, cname: str, data: bytes):
    f.write(f"static const uint8_t {cname}[] PROGMEM = {{\n")
    for i in range(0, len(data), 16):
        f.write("    " + ", ".join(f"0x{b:02x}" for b in data[i : i + 16]) + ",\n")
    f.write("};\n")


def main():
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as f:
        f.write(
            "// Generated by scripts/gen_icons.py from icons/*.svg — do not edit.\n"
            "#pragma once\n\n#include <cstdint>\n\n"
            "#ifndef PROGMEM\n#define PROGMEM\n#endif\n\n"
            "struct IconBmp {\n  const uint8_t* data;\n  uint8_t w, h;\n};\n\n"
        )

        for size in WEATHER_SIZES:
            entries = []
            for name, enum_name in WEATHER:
                cname = f"icon_{name}_{size}"
                emit_array(f, cname, to_bits(render_svg(name, size)))
                entries.append((cname, enum_name))
            f.write(f"\n// Indexed by the WeatherIcon enum (src/model.h).\n")
            f.write(f"static const IconBmp ICON_WEATHER_{size}[] = {{\n")
            for cname, enum_name in entries:
                f.write(f"    {{{cname}, {size}, {size}}},  // {enum_name}\n")
            f.write("};\n\n")

        for size in ARROW_SIZES:
            cnames = []
            for octant in range(8):
                cname = f"icon_arrow_{size}_{octant * 45}"
                emit_array(f, cname, to_bits(rotated_arrow(size, octant * 45)))
                cnames.append(cname)
            f.write(
                f"\n// Octant 0 points north (up), 1 = NE, ... 7 = NW.\n"
                f"static const IconBmp ICON_ARROW_{size}[] = {{\n"
            )
            for cname in cnames:
                f.write(f"    {{{cname}, {size}, {size}}},\n")
            f.write("};\n\n")

        emit_array(f, f"icon_refresh_{REFRESH_SIZE}", to_bits(render_svg("refresh", REFRESH_SIZE)))
        f.write(
            f"\nstatic const IconBmp ICON_REFRESH = "
            f"{{icon_refresh_{REFRESH_SIZE}, {REFRESH_SIZE}, {REFRESH_SIZE}}};\n"
        )

        emit_array(f, "icon_eye_28", to_bits(render_svg("eye", 28)))
        f.write("\nstatic const IconBmp ICON_EYE = {icon_eye_28, 28, 28};\n")

    print(f"wrote {OUT}")


if __name__ == "__main__":
    sys.exit(main())
